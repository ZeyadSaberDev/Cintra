export function translateAdminText(text: string, language: AdminLanguage): string {
  if (language === 'en') return text;
  const leading = text.match(/^\s*/)?.[0] ?? '';
  const trailing = text.match(/\s*$/)?.[0] ?? '';
  const content = text.slice(leading.length, text.length - trailing.length);
  const exact = arabic[content];
  if (exact) return `${leading}${exact}${trailing}`;
  const accounts = content.match(/^([\d,]+) accounts, including guest users\.$/);
  if (accounts) return `${leading}${accounts[1]} حساب، بما فيها حسابات الضيوف.${trailing}`;
  const selected = content.match(/^([\d,]+) selected$/);
  if (selected) return `${leading}${selected[1]} محدد${trailing}`;
  const modelCount = content.match(/^Key (.+) · ([\d,]+) models$/);
  if (modelCount) return `${leading}المفتاح ${modelCount[1]} · ${modelCount[2]} نموذجاً${trailing}`;
  const apiPriority = content.match(/^Priority for (.+)$/);
  if (apiPriority) return `${leading}أولوية ${apiPriority[1]}${trailing}`;
  const primaryApiDeletion = content.match(/^This is the primary API\. Deleting "(.+)" will promote the next active API\. Model definitions and usage records will be kept\.$/);
  if (primaryApiDeletion) {
    return `${leading}هذا هو اتصال API الأساسي. عند حذف "${primaryApiDeletion[1]}" سيصبح اتصال API النشط التالي هو الأساسي. سيتم الاحتفاظ بتعريفات النماذج وسجلات الاستخدام.${trailing}`;
  }
  const apiDeletion = content.match(/^Remove API connection "(.+)"\? Model definitions and usage records will be kept\.$/);
  if (apiDeletion) {
    return `${leading}هل تريد إزالة اتصال API "${apiDeletion[1]}"؟ سيتم الاحتفاظ بتعريفات النماذج وسجلات الاستخدام.${trailing}`;
  }
  const priority = content.match(/^Priority (\d+)$/);
  if (priority) return `${leading}الأولوية ${priority[1]}${trailing}`;
  const activeApis = content.match(/^([\d,]+) active APIs$/);
  if (activeApis) return `${leading}${activeApis[1]} واجهات API نشطة${trailing}`;
  const metricDetails = content.match(/^([\d,]+) registered · ([\d,]+) guests$/);
  if (metricDetails) return `${leading}${metricDetails[1]} مسجل · ${metricDetails[2]} ضيف${trailing}`;
  const successRate = content.match(/^API success ([\d,.]+)%$/);
  if (successRate) return `${leading}نجاح API بنسبة ${successRate[1]}%${trailing}`;
  const bytes = content.match(/^([\d,.]+) MB$/);
  if (bytes) return `${leading}${bytes[1]} ميغابايت${trailing}`;
  const countMessages = content.match(/^([\d,]+) messages · ([\d,]+) tokens · (.+)$/);
  if (countMessages) return `${leading}${countMessages[1]} رسالة · ${countMessages[2]} رمز · ${countMessages[3]}${trailing}`;
  const count = content.match(/^([\d,]+) (registered|guests|active APIs)$/);
  if (count) {
    const label = { registered: 'مسجل', guests: 'ضيف', 'active APIs': 'واجهات API نشطة' }[count[2]];
    return `${leading}${count[1]} ${label}${trailing}`;
  }
  const pageSize = content.match(/^(\d+) \/ page$/);
  if (pageSize) return `${leading}${pageSize[1]} / صفحة${trailing}`;
  const httpStatus = content.match(/^Provider returned HTTP (\d+) while listing models\.$/);
  if (httpStatus) return `${leading}أعاد المزوّد HTTP ${httpStatus[1]} أثناء جلب النماذج.${trailing}`;
  const apiTest = content.match(/^Provider returned HTTP (\d+)\.$/);
  if (apiTest) {
    const reason: Record<string, string> = {
      '401': 'رفض المزوّد مفتاح API.',
      '403': 'رفض المزوّد الوصول لهذا الطلب.',
      '404': 'لم يتم العثور على مسار API أو النموذج.',
    };
    return `${leading}${reason[apiTest[1]] || `أعاد المزوّد HTTP ${apiTest[1]}.`}${trailing}`;
  }
  const requestFailed = content.match(/^Request failed \((\d+)\)\.$/);
  if (requestFailed) return `${leading}فشل الطلب (HTTP ${requestFailed[1]}).${trailing}`;
  const recordsRemoved = content.match(/^(\d+) old messages removed\.$/);
  if (recordsRemoved) return `${leading}تم حذف ${recordsRemoved[1]} رسالة قديمة.${trailing}`;
  const testDuration = content.match(/^(.+) \((\d+) ms\)$/);
  if (testDuration) return `${leading}${translateAdminText(testDuration[1], language)} (${testDuration[2]} مللي ثانية)${trailing}`;
  const importResult = content.match(/^(\d+) models synchronized from (.+)\.$/);
  if (importResult) return `${leading}تمت مزامنة ${importResult[1]} نموذج من ${importResult[2]}.${trailing}`;
  const testing = content.match(/^Testing (.+)…$/);
  if (testing) return `${leading}جارٍ اختبار ${testing[1]}…${trailing}`;
  const syncing = content.match(/^Syncing models from (.+)…$/);
  if (syncing) return `${leading}جارٍ مزامنة النماذج من ${syncing[1]}…${trailing}`;
  const addedEmails = content.match(/^Remove (.+) from the local administrator allowlist\?$/);
  if (addedEmails) return `${leading}إزالة ${addedEmails[1]} من قائمة السماح لمديري النظام؟${trailing}`;
  const ms = content.match(/^(\d+) ms peak$/);
  if (ms) return `${leading}${ms[1]} مللي ثانية (الذروة)${trailing}`;
  const simpleSuffix = content.match(/^(.+?) · usage$/);
  if (simpleSuffix) return `${leading}${simpleSuffix[1]} · الاستخدام${trailing}`;
  const status = content.match(/^Provider returned HTTP (\d+)\.$/);
  if (status) return `${leading}أعاد المزوّد رمز HTTP ${status[1]}.${trailing}`;
  return text;
}

const translatedAttributes = ['aria-label', 'title', 'placeholder', 'description', 'label'] as const;

export function translateAdminNode(node: ReactNode, language: AdminLanguage, busy = false): ReactNode {
  if (typeof node === 'string') return translateAdminText(node, language);
  if (Array.isArray(node)) return node.map((child) => translateAdminNode(child, language, busy));
  if (!isValidElement<{ children?: ReactNode }>(node)) return node;
  const props: Record<string, unknown> = {};
  if (busy && node.type === 'button' && (node.props as { disabled?: boolean }).disabled !== true) {
    props.disabled = true;
  }
  for (const attribute of translatedAttributes) {
    const value = (node.props as Record<string, unknown>)[attribute];
    if (typeof value === 'string') props[attribute] = translateAdminText(value, language);
  }
  const children = (node.props as { children?: ReactNode }).children;
  if (children !== undefined) {
    props.children = Children.map(children, (child) => translateAdminNode(child, language, busy));
  }
  return cloneElement(node, props);
}
